class LogMelSpectrogram(nn.Module):

    def __init__(
        self,
        sample_rate,
        n_fft,
        hop_length,
        win_length,
        n_mels,
        mel_filterbank
    ):

        super().__init__()

        self.n_fft = n_fft
        self.hop_length = hop_length
        self.win_length = win_length

        window = torch.hann_window(
            win_length
        )

        self.register_buffer(
            "window",
            window
        )

        self.register_buffer(
            "mel_filterbank",
            mel_filterbank
        )

    def forward(self, waveform):

        # waveform: [B, T]
        # Force FP32 computation to completely prevent FP16 underflow/NaNs during STFT & log-mel
        with torch.cuda.amp.autocast(enabled=False):
            waveform = waveform.float()

            stft = torch.stft(
                waveform,
                n_fft=self.n_fft,
                hop_length=self.hop_length,
                win_length=self.win_length,
                window=self.window,
                center=True,
                return_complex=True
            )

            # Magnitude
            magnitude = torch.abs(stft)

            # Power
            power = magnitude ** 2

            # Mel projection
            mel = torch.matmul(
                self.mel_filterbank,
                power
            )

            # Log scale: clamp min=1e-5 to guarantee finite log values (prevents -inf / NaN)
            mel = torch.log(
                torch.clamp(mel, min=1e-5)
            )

            # Per-example normalization (Mean-Variance Normalization)
            mean = mel.mean(
                dim=(-2, -1),
                keepdim=True
            )

            std = mel.std(
                dim=(-2, -1),
                keepdim=True
            )

            mel = (mel - mean) / (
                std + 1e-5
            )

            # [B, 1, MELS, TIME]
            mel = mel.unsqueeze(1)

        return mel

