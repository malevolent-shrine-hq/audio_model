class ConvBNAct(nn.Module):

    def __init__(
        self,
        in_channels,
        out_channels,
        kernel_size=3,
        stride=1,
        padding=1
    ):

        super().__init__()

        self.block = nn.Sequential(

            nn.Conv2d(
                in_channels,
                out_channels,
                kernel_size,
                stride,
                padding,
                bias=False
            ),

            nn.BatchNorm2d(
                out_channels
            ),

            nn.SiLU(
                inplace=True
            )
        )

    def forward(self, x):
        return self.block(x)


class SEBlock(nn.Module):

    def __init__(
        self,
        channels,
        reduction=8
    ):

        super().__init__()

        hidden = max(
            channels // reduction,
            8
        )

        self.pool = nn.AdaptiveAvgPool2d(1)

        self.fc = nn.Sequential(

            nn.Linear(
                channels,
                hidden
            ),

            nn.SiLU(),

            nn.Linear(
                hidden,
                channels
            ),

            nn.Sigmoid()
        )

    def forward(self, x):

        b, c, _, _ = x.shape

        y = self.pool(x)
        y = y.flatten(1)
        y = self.fc(y)
        y = y.view(b, c, 1, 1)

        return x * y


class ResidualSEBlock(nn.Module):

    def __init__(
        self,
        in_channels,
        out_channels,
        stride=1,
        dropout=0.0
    ):

        super().__init__()

        self.conv1 = ConvBNAct(
            in_channels,
            out_channels,
            stride=stride
        )

        self.conv2 = nn.Sequential(

            nn.Conv2d(
                out_channels,
                out_channels,
                3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(
                out_channels
            )
        )

        self.se = SEBlock(
            out_channels
        )

        self.dropout = nn.Dropout2d(
            dropout
        )

        if (
            in_channels != out_channels
            or stride != 1
        ):

            self.shortcut = nn.Sequential(

                nn.Conv2d(
                    in_channels,
                    out_channels,
                    1,
                    stride=stride,
                    bias=False
                ),

                nn.BatchNorm2d(
                    out_channels
                )
            )

        else:

            self.shortcut = nn.Identity()

        self.activation = nn.SiLU(
            inplace=True
        )

    def forward(self, x):

        identity = self.shortcut(x)

        out = self.conv1(x)

        out = self.conv2(out)

        out = self.se(out)

        out = self.dropout(out)

        out = out + identity

        return self.activation(out)


