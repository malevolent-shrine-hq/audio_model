import soundfile as sf
from scipy.signal import resample_poly


def load_audio(path, target_sr=SAMPLE_RATE, training=False):
    """
    Load audio, convert to mono, resample if necessary,
    then force exactly NUM_SAMPLES samples (with random crop during training).
    """

    audio, sr = sf.read(path, dtype="float32", always_2d=False)

    # Convert stereo -> mono
    if audio.ndim == 2:
        audio = np.mean(audio, axis=1)

    audio = np.asarray(audio, dtype=np.float32)

    # Replace invalid values
    audio = np.nan_to_num(
        audio,
        nan=0.0,
        posinf=0.0,
        neginf=0.0
    )

    # Resample if required
    if sr != target_sr:

        gcd = math.gcd(int(sr), int(target_sr))

        up = target_sr // gcd
        down = sr // gcd

        audio = resample_poly(
            audio,
            up,
            down
        ).astype(np.float32)

    # Remove DC offset
    if len(audio) > 0:
        audio = audio - np.mean(audio)

    # Normalize safely
    max_abs = np.max(np.abs(audio)) if len(audio) else 0

    if max_abs > 1e-8:
        audio = audio / max_abs

    # Force exactly NUM_SAMPLES (2 seconds)
    if len(audio) < NUM_SAMPLES:

        audio = np.pad(
            audio,
            (0, NUM_SAMPLES - len(audio))
        )

    elif len(audio) > NUM_SAMPLES:

        if training:
            # Random crop during training to capture speech anywhere in the clip
            start = random.randint(0, len(audio) - NUM_SAMPLES)
            audio = audio[start : start + NUM_SAMPLES]
        else:
            # Consistent start crop for validation and testing
            audio = audio[:NUM_SAMPLES]

    return audio.astype(np.float32)

