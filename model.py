    print("File:", audio_path)

    # Load audio
    audio = load_audio_for_prediction(
        audio_path
    )

    audio = audio.unsqueeze(0).to(DEVICE)

    print("Audio shape:", audio.shape)

    # --------------------------------------------------------
    # Mel spectrogram
    # --------------------------------------------------------

    global mel_transform
    if "mel_transform" not in globals() or mel_transform is None:
        mel_transform = LogMelSpectrogram(
            sample_rate=SAMPLE_RATE,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            win_length=WIN_LENGTH,
            n_mels=N_MELS,
            mel_filterbank=MEL_FILTERBANK
        ).to(DEVICE)

    with torch.no_grad():

        mel = mel_transform(audio)

        # Safety
        mel = torch.nan_to_num(
            mel,
            nan=0.0,
            posinf=0.0,
            neginf=0.0
        )

        # ----------------------------------------------------
        # CNN
        # ----------------------------------------------------

        logits = model(mel)

        logits = torch.nan_to_num(
            logits,
            nan=0.0,
            posinf=20.0,
            neginf=-20.0
        )

        # ----------------------------------------------------
        # Probability
        # ----------------------------------------------------

        fake_probability = torch.sigmoid(
            logits
        ).item()

    real_probability = 1.0 - fake_probability

    # --------------------------------------------------------
    # Classification
    # --------------------------------------------------------

    if fake_probability >= threshold:

        prediction = "AI-GENERATED / FAKE"

    else:

        prediction = "REAL / BONAFIDE"

    confidence = max(
        fake_probability,
        real_probability
    )

    # --------------------------------------------------------
    # Result
    # --------------------------------------------------------

    print()
    print("RESULT")
    print("-" * 60)

    print(
        f"Fake probability : {fake_probability * 100:.2f}%"
    )

    print(
        f"Real probability : {real_probability * 100:.2f}%"
    )

    print(
        f"Confidence       : {confidence * 100:.2f}%"
    )

    print(
        f"Threshold        : {threshold:.4f}"
    )

    print()
    print("Prediction:", prediction)

    print("=" * 60)

    return {
        "file": audio_path,
        "fake_probability": fake_probability,
        "real_probability": real_probability,
        "confidence": confidence,
        "prediction": prediction
    }

