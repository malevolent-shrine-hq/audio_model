    candidates = []

    for p in root.rglob("*"):
        if not p.is_dir():
            continue

        name = p.name.lower()

        if name != split_name.lower():
            continue

        fake_dir = p / "fake"
        real_dir = p / "real"

        if fake_dir.exists() and real_dir.exists():
            candidates.append(p)

    return candidates


