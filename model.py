class SpecAugment(nn.Module):

    def __init__(
        self,
        freq_mask=12,
        time_mask=15
    ):

        super().__init__()

        self.freq_mask = freq_mask
        self.time_mask = time_mask

    def forward(self, x):

        if not self.training:
            return x

        B, C, FREQ, TIME = x.shape
        x = x.clone()

        # Apply masking per-sample independently across the batch
        for b in range(B):
            # Frequency masking
            for _ in range(2):

                width = random.randint(
                    0,
                    min(self.freq_mask, FREQ - 1)
                )

                if width > 0:

                    start = random.randint(
                        0,
                        FREQ - width
                    )

                    x[
                        b,
                        :,
                        start:start + width,
                        :
                    ] = 0.0

            # Time masking
            for _ in range(2):

                width = random.randint(
                    0,
                    min(self.time_mask, TIME - 1)
                )

                if width > 0:

                    start = random.randint(
                        0,
                        TIME - width
                    )

                    x[
                        b,
                        :,
                        :,
                        start:start + width
                    ] = 0.0

        return x

