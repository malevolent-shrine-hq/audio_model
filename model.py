def train_one_epoch(
    model,
    loader,
    optimizer,
    criterion,
    epoch
):

    model.train()
    mel_transform.train()
    spec_augment.train()

    running_loss = 0.0

    all_probs = []
    all_labels = []

    start_time = time.time()

    for batch_idx, (
        audio,
        labels,
        _
    ) in enumerate(loader):

        audio = audio.to(
            DEVICE,
            non_blocking=True
        )

        labels = labels.to(
            DEVICE,
            non_blocking=True
        )

        optimizer.zero_grad(
            set_to_none=True
        )

        with torch.cuda.amp.autocast(
            enabled=USE_AMP
        ):

            mel = mel_transform(
                audio
            )

            mel = spec_augment(
                mel
            )

            logits = model(
                mel
            )

            loss = criterion(
                logits,
                labels
            )

        scaler.scale(
            loss
        ).backward()

        scaler.unscale_(
            optimizer
        )

        torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            MAX_GRAD_NORM
        )

        scaler.step(
            optimizer
        )

        scaler.update()

        running_loss += (
            loss.item() *
            audio.size(0)
        )

        probs = torch.sigmoid(
            logits
        )

        all_probs.extend(
            probs.detach().cpu().numpy()
        )

        all_labels.extend(
            labels.detach().cpu().numpy()
        )

        # Scheduler
        scheduler.step(
            epoch +
            batch_idx / len(loader)
        )

        if batch_idx % 100 == 0:

            print(
                f"\rEpoch {epoch + 1} | "
                f"Batch {batch_idx}/{len(loader)} | "
                f"Loss {loss.item():.4f}",
                end=""
            )

    print()

    epoch_loss = (
        running_loss /
        len(loader.dataset)
    )

    metrics = calculate_metrics(
        all_labels,
        all_probs
    )

    elapsed = time.time() - start_time

    return epoch_loss, metrics, elapsed

