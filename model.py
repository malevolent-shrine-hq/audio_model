def hz_to_mel(hz):
    return 2595.0 * np.log10(1.0 + hz / 700.0)


def mel_to_hz(mel):
    return 700.0 * (10.0 ** (mel / 2595.0) - 1.0)


def create_mel_filterbank(
    sample_rate,
    n_fft,
    n_mels,
    f_min,
    f_max
):

    # Mel points
    mel_min = hz_to_mel(f_min)
    mel_max = hz_to_mel(f_max)

    mel_points = np.linspace(
        mel_min,
        mel_max,
        n_mels + 2
    )

    hz_points = mel_to_hz(mel_points)

    # FFT frequencies
    fft_freqs = np.linspace(
        0,
        sample_rate / 2,
        n_fft // 2 + 1
    )

    filterbank = np.zeros(
        (n_mels, n_fft // 2 + 1),
        dtype=np.float32
    )

    for m in range(1, n_mels + 1):

        left = hz_points[m - 1]
        center = hz_points[m]
        right = hz_points[m + 1]

        # Rising slope
        left_indices = np.where(
            (fft_freqs >= left) &
            (fft_freqs <= center)
        )[0]

        if center > left:
            filterbank[m - 1, left_indices] = (
                (fft_freqs[left_indices] - left) /
                (center - left)
            )

        # Falling slope
        right_indices = np.where(
            (fft_freqs >= center) &
            (fft_freqs <= right)
        )[0]

        if right > center:
            filterbank[m - 1, right_indices] = (
                (right - fft_freqs[right_indices]) /
                (right - center)
            )

    return torch.tensor(filterbank, dtype=torch.float32)


