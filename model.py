class VoiceDataset(Dataset):

    def __init__(
        self,
        files,
        training=False
    ):

        self.files = files
        self.training = training

    def __len__(self):
        return len(self.files)

    def waveform_augmentation(self, audio):

        audio = torch.from_numpy(audio)

        # ------------------------------------
        # Random gain
        # ------------------------------------

        if random.random() < 0.5:

            gain_db = random.uniform(-3.0, 3.0)

            gain = 10 ** (gain_db / 20.0)

            audio = audio * gain

        # ------------------------------------
        # Random noise
        # ------------------------------------

        if random.random() < 0.30:

            noise_level = random.uniform(
                0.001,
                0.01
            )

            noise = torch.randn_like(audio)

            audio = audio + noise_level * noise

        # ------------------------------------
        # Small time shift
        # ------------------------------------

        if random.random() < 0.30:

            shift = random.randint(
                -800,
                800
            )

            audio = torch.roll(
                audio,
                shifts=shift,
                dims=0
            )

        # ------------------------------------
        # Clamp
        # ------------------------------------

        audio = torch.clamp(
            audio,
            -1.0,
            1.0
        )

        return audio

    def __getitem__(self, index):

        path, label = self.files[index]

        audio = load_audio(path, training=self.training)

        # Augment only training data
        if self.training:
            audio = self.waveform_augmentation(audio)
        else:
            audio = torch.from_numpy(audio)

        return audio, torch.tensor(
            label,
            dtype=torch.float32
        ), path


